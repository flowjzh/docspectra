"""The anydoc engine — docx sweep (body, text boxes, tables), office
image assets, pdf gate parity, and the legacy .doc family."""

from pathlib import Path

import pytest

from docspectra.parser import ParseDeclinedError, configure, parse
from tests.docx_builder import make_docx
from tests.pdf_builder import make_pdf, raster_pdf, strip_pdf

CLEAN = make_docx()  # text box + table + header, no media
MEDIA = make_docx(media=True)  # + word/media/image1.png, inline-referenced
RASTER = raster_pdf()
STRIP = strip_pdf()

FIXTURES = Path(__file__).parent / 'fixtures'

@pytest.fixture
def anydoc_chain():
    configure({'docx': ['anydoc'], 'doc': ['anydoc'], 'pdf': ['anydoc']})
    yield
    configure(None)


async def test_text_box_table_and_body_present(anydoc_chain):
    result = await parse(CLEAN, name='resume.docx')
    assert result.provider == 'anydoc'
    assert 'body paragraph one' in result.text
    assert 'text box content' in result.text  # typed-API-blind fixture
    assert 'cell A1' in result.text and 'cell B2' in result.text
    assert 'header line' not in result.text  # page furniture, dropped by design


async def test_media_docx_carries_its_image_as_asset(anydoc_chain):
    # images stay local as ImageAssets, never declined to the cloud
    result = await parse(MEDIA, name='resume.docx')
    assert result.provider == 'anydoc'
    assert len(result.images) == 1
    asset = result.images[0]
    assert asset.name == 'word/media/image1.png'
    assert asset.mime == 'image/png'
    assert asset.source == 'anydoc word/media/image1.png'
    assert result.meta['skipped_assets'] == 0


async def test_legacy_doc_parses_locally(anydoc_chain):
    # Word-97 OLE2, generated by a real Word export of two synthetic
    # sentences (committed fixture — no corpus data, no external file)
    result = await parse((FIXTURES / 'legacy.doc').read_bytes(), name='legacy.doc')
    assert result.provider == 'anydoc'
    assert 'legacy body paragraph' in result.text
    assert 'second line of the legacy doc' in result.text


async def test_raster_pdf_declines_classify_gate(anydoc_chain):
    with pytest.raises(ParseDeclinedError) as exc:
        await parse(RASTER, name='resume.pdf')
    assert exc.value.attempts[0].reason == 'classify_gate'


async def test_word_strip_declines_fingerprint_gate(anydoc_chain):
    with pytest.raises(ParseDeclinedError) as exc:
        await parse(STRIP, name='resume.pdf')
    assert exc.value.attempts[0].reason == 'fingerprint_gate'


async def test_clean_pdf_parses(anydoc_chain):
    result = await parse(make_pdf(), name='resume.pdf')
    assert result.provider == 'anydoc'
    assert 'sample line 001' in result.text


async def test_csv_names_its_format(anydoc_chain):
    # csv carries no signature: the extension must reach the engine
    result = await parse(b'name,city\nAlice,Berlin\n', name='sheet.csv')
    assert result.provider == 'anydoc'
    assert 'Alice' in result.text
